# shellcheck shell=bash
# What platform/linux/install.sh puts in place: the installation (~/.local/share/kanata-nicola/) and the systemd
# user units that run it.
#
# Usage:  source platform/linux/install-files.sh
#         nicola_install_files <repository> <bin dir> <dir> [kanata]   copies the programs and scripts into <dir>
#         nicola_unit_kanata <repository> <dir> <settings dir>         prints kanata-nicola.service
#         nicola_unit_imesync <repository> <dir> <settings dir>        prints kanata-nicola-imesync.service
#         The unit functions return 1 (with a message) if systemd cannot run the command from its path.
#         The units give service.sh the settings directory (the one when install.sh ran): XDG_CONFIG_HOME may
#         be unset in the environment of the systemd user manager at login.

# The installation: the generator and nicola-imesync from <bin dir>, the scripts the units run (service.sh reads
# the settings with config.sh), the bundled overlays, and kanata if given (none when NICOLA_KANATA_BIN names one).
nicola_install_files() {
  local repo=$1 bin=$2 dir=$3 kanata=${4:-}
  mkdir -p "$dir/layouts/overlays" || return 1
  install -m 755 "$bin/nicola-kbdgen" "$bin/nicola-imesync" "$repo/platform/linux/service.sh" "$dir/" || return 1
  install -m 644 "$repo/platform/linux/config.sh" "$dir/" || return 1
  install -m 644 "$repo"/layouts/overlays/*.toml "$dir/layouts/overlays/" || return 1
  if [[ -n "$kanata" ]]; then
    install -m 755 "$kanata" "$dir/kanata" || return 1
  fi
}

# Quotes a command and its arguments for ExecStart= of a unit file: each in double quotes, with \ and "
# escaped and % written as %% (no specifiers). In the arguments, $ is written as $$ (no variable
# expansion); systemd does not expand the command's own path, so there it stays as is.
systemd_args() {
  local a out=() first=1
  for a in "$@"; do
    a=${a//\\/\\\\}
    a=${a//\"/\\\"}
    ((first)) || a=${a//\$/\$\$}
    first=0
    a=${a//%/%%}
    out+=("\"$a\"")
  done
  echo "${out[*]}"
}

# systemd refuses a command path with " or \ in it, however quoted.
systemd_check_command() {
  if [[ "$1" == *[\"\\]* ]]; then
    echo "systemd cannot run a command whose path has \" or \\ in it: $1" >&2
    return 1
  fi
}

# Documentation= of a unit file takes URIs: percent-encode what is not plain, and write % as %%.
systemd_doc_uri() {
  local path=$1 uri="file://" c i LC_ALL=C  # byte by byte (UTF-8 is encoded per byte)
  for ((i = 0; i < ${#path}; i++)); do
    c=${path:i:1}
    if [[ "$c" == [A-Za-z0-9/._~-] ]]; then
      uri+=$c
    else
      uri+=$(printf '%%%%%02X' "'$c")
    fi
  done
  echo "$uri"
}

nicola_unit_kanata() {
  local repo=$1 dir=$2 settings=$3
  systemd_check_command "$dir/service.sh" || return 1
  cat <<UNIT
# generated by $repo/platform/linux/install.sh — DO NOT EDIT
[Unit]
Description=kanata-nicola (NICOLA thumb-shift)
Documentation=$(systemd_doc_uri "$repo/docs/usage.md")
# Started with it (it runs only when the settings turn IME sync on).
Wants=kanata-nicola-imesync.service
# Started with the graphical session (WantedBy= below), stopped at its end (logout), started again at the next login.
# kanata holds all the keyboards of the machine: without a graphical session of this user (logged in over ssh only, or
# lingering from boot), or after it (a user service can outlive the session), the login screen and the next user
# would type through it, in the NICOLA layer if it was on.
PartOf=graphical-session.target
# If start keeps failing (e.g. keyboard contention), give up after 5 tries within 1 minute.
StartLimitIntervalSec=60
StartLimitBurst=5

[Service]
Type=simple
# Reads the settings at every start: makes the kanata configuration in the runtime directory, checks it, runs kanata.
ExecStart=$(systemd_args "$dir/service.sh" kanata "$settings")
# The name of the log lines (otherwise service.sh, for both units).
SyslogIdentifier=kanata
RuntimeDirectory=kanata-nicola
# Restart only after an abnormal exit. The emergency stop (Left Ctrl + Space + Esc) ends kanata with SIGTERM,
# which systemd counts as a clean exit, so it is not restarted; nor after a mistake in the settings (78).
Restart=on-failure
RestartPreventExitStatus=78
RestartSec=2

[Install]
# Not default.target, which the user manager starts at any login (ssh too) and with lingering at boot.
WantedBy=graphical-session.target
# systemctl --user enable/disable kanata-nicola does the same to nicola-imesync. Disabled alone, kanata-nicola would
# still start at login: nicola-imesync starts with the graphical session and starts it (BindsTo=).
Also=kanata-nicola-imesync.service
UNIT
}

nicola_unit_imesync() {
  local repo=$1 dir=$2 settings=$3
  systemd_check_command "$dir/service.sh" || return 1
  cat <<UNIT
# generated by $repo/platform/linux/install.sh — DO NOT EDIT
[Unit]
Description=nicola-imesync (follow fcitx5+Mozc state and switch the kanata NICOLA layer)
Documentation=$(systemd_doc_uri "$repo/docs/usage.md")
After=graphical-session.target kanata-nicola.service
# Runs only with its own kanata: stopped and restarted with kanata-nicola, so that restarting it applies the settings
# to both, and stopped when that kanata stops by itself (the emergency stop) or fails. Otherwise it would switch the
# layer of whatever listens on the port, such as the kanata of another user who switched users without logging out.
BindsTo=kanata-nicola.service
# It reads the IME over the D-Bus session bus.
PartOf=graphical-session.target

[Service]
Type=simple
# Runs only when the settings turn IME sync on (NICOLA_IME_SYNC=1).
ExecCondition=$(systemd_args "$dir/service.sh" ime-sync-on "$settings")
ExecStart=$(systemd_args "$dir/service.sh" imesync "$settings")
SyslogIdentifier=nicola-imesync
# Not Restart=always: systemd 249 restarts it after ExecCondition= says no, again and again.
Restart=on-failure
RestartSec=2

[Install]
WantedBy=graphical-session.target
UNIT
}
